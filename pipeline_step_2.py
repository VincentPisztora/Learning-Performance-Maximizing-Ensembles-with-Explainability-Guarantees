def init_model(model_type,arch_hyper_dict):
    print('Warning (init_model): Categorical predictors are not supported')
    if model_type == 'classification_tree':
        model = DecisionTreeClassifier(random_state=0)
    elif model_type == 'logistic_regression':
        model = LogisticRegression(random_state=0,solver='saga',penalty='l1',max_iter=1e4)
    elif model_type == 'gradient_boosting_trees_classifier':
        model = GradientBoostingClassifier(random_state=0)
    elif model_type == 'regression_tree':
        model = DecisionTreeRegressor(random_state=0)
    elif model_type == 'regression':
        model = Lasso(random_state=0,selection='random',max_iter=1e4)
    elif model_type == 'gradient_boosting_trees_regressor':
        model = GradientBoostingRegressor(random_state=0)
    elif model_type == 'dnn':
        model = TabWRN(output_size=arch_hyper_dict.get('pred_dim'),
                       with_top=True,
                       num_base_nodes=arch_hyper_dict.get('n_base_nodes'),
                       N=arch_hyper_dict.get('N'),
                       k=arch_hyper_dict.get('k'),
                       drop_p=arch_hyper_dict.get('drop_p'),
                       weight_decay=arch_hyper_dict.get('weight_decay'),
                       categorical_features_indicator_dict=arch_hyper_dict.get('categorical_features_indicator_dict'),
                       categorical_features_vocabulary_size_dict=arch_hyper_dict.get('categorical_features_vocabulary_size_dict'),
                       embedding_output_dim=arch_hyper_dict.get('embedding_output_dim'))
    else:
        raise ValueError('init_model: This model_arch not implemented')
    
    return model
    


def supervised_tune_and_train(prefix,model,model_type,ds_dict,pred_dim_underlying,train_split,split_type,split_i,loss_fn,opt,batch_size=64,epochs=400,save_name_params={}):
    ds_sklearn = ds_dict.get('ds_sklearn')
    ds_tensorflow = ds_dict.get('ds_tensorflow')
    
    problem_type = ds_dict.get('problem_type')
    
    train_index = train_split[1]
    
    if model_type == 'dnn':
        dir_model = os.path.join(prefix,model_type+'_opt_'+save_name_params.get('opt')+'_sch_'+save_name_params.get('sch')+'_lr_'+save_name_params.get('lr')+'_wd_'+save_name_params.get('wd'))
        Path(dir_model).mkdir(parents=True, exist_ok=True)
    else:
        dir_model = os.path.join(prefix,model_type)
        Path(dir_model).mkdir(parents=True, exist_ok=True)
    
    if model_type == 'dnn':
        print('Fitting tf_dnn...')
        start_time = time()
        
        tf_ds_train_subset = get_subsetted_tf_ds(ds_sk=ds_sklearn.get('ds_train'),idx=train_index,categorical_indicator=ds_dict.get('categorical_indicator'),embeddings=ds_dict.get('embeddings_tf'),problem_type=problem_type)
        
        model = simpleSupervisedTrainTF(model=model,
                                        train_dataset=tf_ds_train_subset,
                                        val_dataset=ds_tensorflow.get('ds_val'),
                                        test_dataset=ds_tensorflow.get('ds_test'),
                                        batch_size=batch_size,epochs=epochs,
                                        loss_fn=loss_fn,opt=opt,
                                        prefix=os.path.join(dir_model,'training_losses_'+str(split_type)+'_'+str(split_i)+'_'))
        print('----------\nFitting complete\n','duration:',np.round((time()-start_time)/60,2),'min')
        
    elif model_type == 'classification_tree':
        print('Tuning sklearn_classification_tree...')
        start_time = time()
        param_grid = {'max_depth':[2**i for i in range(1,12)],
                      'min_samples_split':[2**i for i in range(1,12)],
                      'max_leaf_nodes':[2**i for i in range(1,12)]}
        base_estimator = DecisionTreeClassifier()
        cv_folds = RepeatedStratifiedKFold(n_splits=n_splits,n_repeats=1,random_state=0)
        grid_search = GridSearchCV(estimator=base_estimator,param_grid=param_grid,n_jobs=-1,cv=cv_folds,scoring='accuracy',verbose=1)
        search_results = grid_search.fit(X=np.take(ds_sklearn.get('ds_train').get('x_train'),train_index,0),y=np.take(ds_sklearn.get('ds_train').get('y_train'),train_index,0))
        wb = search_results.best_estimator_
        print('----------\nTuning complete\nbest estimator:',wb,'\n','cv acc:',np.round(search_results.best_score_*100,2),'\n','duration:',np.round((time()-start_time)/60,2),'min')
        pd.DataFrame.from_dict(search_results.cv_results_).to_csv(os.path.join(prefix,model_type,'cv_results_classification_tree_'+str(split_type)+'_'+str(split_i)+'.csv'))
    elif model_type == 'logistic_regression':
        print('Tuning sklearn_logistic_regression...')
        start_time = time()
        param_grid = {'C':[2**i for i in range(-10,10,1)]}
        base_estimator = LogisticRegression(random_state=0,solver='saga',penalty='l1',max_iter=1e4) 
        cv_folds = RepeatedStratifiedKFold(n_splits=n_splits,n_repeats=1,random_state=0)
        grid_search = GridSearchCV(estimator=base_estimator,param_grid=param_grid,n_jobs=-1,cv=cv_folds,scoring='accuracy',verbose=1)
        search_results = grid_search.fit(X=np.take(ds_sklearn.get('ds_train').get('x_train'),train_index,0),y=np.take(ds_sklearn.get('ds_train').get('y_train'),train_index,0))
        wb = search_results.best_estimator_
        print('----------\nTuning complete\nbest estimator:',wb,'\n','cv acc:',np.round(search_results.best_score_*100,2),'\n','duration:',np.round((time()-start_time)/60,2),'min')
        pd.DataFrame.from_dict(search_results.cv_results_).to_csv(os.path.join(prefix,model_type,'cv_results_logisitic_regression_'+str(split_type)+'_'+str(split_i)+'.csv'))
    elif model_type == 'gradient_boosting_trees_classifier':
        print('Tuning sklearn_gradient_boosting_trees_classifier...')
        start_time = time()
        param_grid = {'learning_rate':[10**i for i in range(-3,0,1)], 
                      'n_estimators':[2**i for i in range(4,10,1)], 
                      'max_depth':[2**i for i in range(3,7,1)], 
                      'subsample':[2e-1*i for i in range(1,6,1)]} 
        base_estimator = GradientBoostingClassifier(random_state=0)
        cv_folds = RepeatedStratifiedKFold(n_splits=n_splits,n_repeats=1,random_state=0)
        grid_search = GridSearchCV(estimator=base_estimator,param_grid=param_grid,n_jobs=-1,cv=cv_folds,scoring='accuracy',verbose=1)
        search_results = grid_search.fit(X=np.take(ds_sklearn.get('ds_train').get('x_train'),train_index,0),y=np.take(ds_sklearn.get('ds_train').get('y_train'),train_index,0))
        wb = search_results.best_estimator_
        print('----------\nTuning complete\nbest estimator:',wb,'\n','cv acc:',np.round(search_results.best_score_*100,2),'\n','duration:',np.round((time()-start_time)/60,2),'min')
        pd.DataFrame.from_dict(search_results.cv_results_).to_csv(os.path.join(prefix,model_type,'cv_results_gradient_boosting_trees_classifier_'+str(split_type)+'_'+str(split_i)+'.csv'))
    elif model_type == 'regression_tree':
        print('Tuning sklearn_regression_tree...')
        start_time = time()
        param_grid = {'max_depth':[2**i for i in range(1,12)],
                      'min_samples_split':[2**i for i in range(1,12)],
                      'max_leaf_nodes':[2**i for i in range(1,12)]}
        base_estimator = DecisionTreeRegressor()
        cv_folds = RepeatedKFold(n_splits=n_splits,n_repeats=1,random_state=0)
        grid_search = GridSearchCV(estimator=base_estimator,param_grid=param_grid,n_jobs=-1,cv=cv_folds,scoring='neg_mean_squared_error',verbose=1)
        search_results = grid_search.fit(X=np.take(ds_sklearn.get('ds_train').get('x_train'),train_index,0),y=np.take(ds_sklearn.get('ds_train').get('y_train'),train_index,0))
        wb = search_results.best_estimator_
        print('----------\nTuning complete\nbest estimator:',wb,'\n','cv acc:',np.round(search_results.best_score_*100,2),'\n','duration:',np.round((time()-start_time)/60,2),'min')
        pd.DataFrame.from_dict(search_results.cv_results_).to_csv(os.path.join(prefix,model_type,'cv_results_regression_tree_'+str(split_type)+'_'+str(split_i)+'.csv'))
    elif model_type == 'regression':
        print('Tuning sklearn_regression...')
        start_time = time()
        param_grid = {'alpha':[2**i for i in range(-10,10,1)]}
        base_estimator = Lasso(random_state=0,selection='random',max_iter=1e4) 
        cv_folds = RepeatedKFold(n_splits=n_splits,n_repeats=1,random_state=0)
        grid_search = GridSearchCV(estimator=base_estimator,param_grid=param_grid,n_jobs=-1,cv=cv_folds,scoring='neg_mean_squared_error',verbose=1)
        search_results = grid_search.fit(X=np.take(ds_sklearn.get('ds_train').get('x_train'),train_index,0),y=np.take(ds_sklearn.get('ds_train').get('y_train'),train_index,0))
        wb = search_results.best_estimator_
        print('----------\nTuning complete\nbest estimator:',wb,'\n','cv acc:',np.round(search_results.best_score_*100,2),'\n','duration:',np.round((time()-start_time)/60,2),'min')
        pd.DataFrame.from_dict(search_results.cv_results_).to_csv(os.path.join(prefix,model_type,'cv_results_regression_'+str(split_type)+'_'+str(split_i)+'.csv'))
    elif model_type == 'gradient_boosting_trees_regressor':
        print('Tuning sklearn_gradient_boosting_trees_regressor...')
        start_time = time()
        param_grid = {'learning_rate':[10**i for i in range(-3,0,1)], 
                      'n_estimators':[2**i for i in range(4,10,1)], 
                      'max_depth':[2**i for i in range(3,7,1)], 
                      'subsample':[2e-1*i for i in range(1,6,1)]} 
        base_estimator = GradientBoostingRegressor(random_state=0)
        cv_folds = RepeatedKFold(n_splits=n_splits,n_repeats=1,random_state=0)
        grid_search = GridSearchCV(estimator=base_estimator,param_grid=param_grid,n_jobs=-1,cv=cv_folds,scoring='neg_mean_squared_error',verbose=1)
        search_results = grid_search.fit(X=np.take(ds_sklearn.get('ds_train').get('x_train'),train_index,0),y=np.take(ds_sklearn.get('ds_train').get('y_train'),train_index,0))
        wb = search_results.best_estimator_
        print('----------\nTuning complete\nbest estimator:',wb,'\n','cv acc:',np.round(search_results.best_score_*100,2),'\n','duration:',np.round((time()-start_time)/60,2),'min')
        pd.DataFrame.from_dict(search_results.cv_results_).to_csv(os.path.join(prefix,model_type,'cv_results_gradient_boosting_trees_regressor_'+str(split_type)+'_'+str(split_i)+'.csv'))
    else:
        raise ValueError('supervised_tune_and_train: This model_type not implemented')
    
    if model_type == 'dnn':
        y_hat_train = []
        for step,(x_i,y_i) in enumerate(tqdm(ds_tensorflow.get('ds_train').batch(batch_size))):
            y_hat_i = model(x_i,training=False)
            y_hat_train.append(y_hat_i)
        
        y_hat_val = []
        for step,(x_i,y_i) in enumerate(tqdm(ds_tensorflow.get('ds_val').batch(batch_size))):
            y_hat_i = model(x_i,training=False)
            y_hat_val.append(y_hat_i)
        
        y_hat_test = []
        for step,(x_i,y_i) in enumerate(tqdm(ds_tensorflow.get('ds_test').batch(batch_size))):
            y_hat_i = model(x_i,training=False)
            y_hat_test.append(y_hat_i)
        
        if problem_type == 'classification':
            y_hat_train = tf.nn.softmax(tf.concat(y_hat_train,0)).numpy()
            y_hat_val = tf.nn.softmax(tf.concat(y_hat_val,0)).numpy()
            y_hat_test = tf.nn.softmax(tf.concat(y_hat_test,0)).numpy()
        elif problem_type == 'regression':
            y_hat_train = tf.concat(y_hat_train,0).numpy()
            y_hat_val = tf.concat(y_hat_val,0).numpy()
            y_hat_test = tf.concat(y_hat_test,0).numpy()
        else:
            raise ValueError('supervised_tune_and_train: This problem_type is not implemented')
    else:
        if problem_type == 'classification':
            y_hat_train = wb.predict_proba(X=ds_sklearn.get('ds_train').get('x_train'))
            y_hat_val = wb.predict_proba(X=ds_sklearn.get('ds_val').get('x_val'))
            y_hat_test = wb.predict_proba(X=ds_sklearn.get('ds_test').get('x_test'))
        elif problem_type == 'regression':
            y_hat_train = wb.predict(X=ds_sklearn.get('ds_train').get('x_train'))
            y_hat_val = wb.predict(X=ds_sklearn.get('ds_val').get('x_val'))
            y_hat_test = wb.predict(X=ds_sklearn.get('ds_test').get('x_test'))
            if len(y_hat_train.shape)==1:
                y_hat_train = np.expand_dims(y_hat_train,-1)
                y_hat_val = np.expand_dims(y_hat_val,-1)
                y_hat_test = np.expand_dims(y_hat_test,-1)
        else:
            raise ValueError('supervised_tune_and_train: This problem_type is not implemented')
        
    pred_dim = y_hat_train.shape[1]
    pd_y_hat_train = pd.DataFrame(y_hat_train,columns=['y_hat_'+str(i) for i in range(pred_dim)])
    pd_y_hat_val = pd.DataFrame(y_hat_val,columns=['y_hat_'+str(i) for i in range(pred_dim)])
    pd_y_hat_test = pd.DataFrame(y_hat_test,columns=['y_hat_'+str(i) for i in range(pred_dim)])
    
    pd_y_hat_train.to_csv(os.path.join(dir_model,'y_hat_train_'+str(split_type)+'_'+str(split_i)+'.csv'))
    pd_y_hat_val.to_csv(os.path.join(dir_model,'y_hat_val_'+str(split_type)+'_'+str(split_i)+'.csv'))
    pd_y_hat_test.to_csv(os.path.join(dir_model,'y_hat_test_'+str(split_type)+'_'+str(split_i)+'.csv'))
    
    #--------------------------------------------------------------------------
        
    if problem_type == 'classification':
        y_train = ds_sklearn.get('ds_train').get('y_train').astype(np.int32)
        y_val = ds_sklearn.get('ds_val').get('y_val').astype(np.int32)
        y_test = ds_sklearn.get('ds_test').get('y_test').astype(np.int32)
        
        y_train = np.eye(pred_dim_underlying)[y_train].astype(np.float32)
        y_val = np.eye(pred_dim_underlying)[y_val].astype(np.float32)
        y_test = np.eye(pred_dim_underlying)[y_test].astype(np.float32)
        
        acc_random_train = np.max(np.mean(y_train,0))*100
        acc_train = np.mean(np.argmax(y_train,1)==np.argmax(y_hat_train,1))*100
        
        acc_random_val = np.max(np.mean(y_val,0))*100
        acc_val = np.mean(np.argmax(y_val,1)==np.argmax(y_hat_val,1))*100
        
        acc_random_test = np.max(np.mean(y_test,0))*100
        acc_test = np.mean(np.argmax(y_test,1)==np.argmax(y_hat_test,1))*100
        
        print('\naccuracies: train (random,wb)', np.round(acc_random_train,2), np.round(acc_train,2))
        print('accuracies: val (random,wb)', np.round(acc_random_val,2), np.round(acc_val,2))
        print('accuracies: test (random,wb)', np.round(acc_random_test,2), np.round(acc_test,2))
        
        pd_acc = pd.DataFrame([[acc_random_train, acc_train],
                               [acc_random_val, acc_val],
                               [acc_random_test, acc_test]],
                              index=['train_ds','val_ds','test_ds'],
                              columns=['random_underlying_acc','model_underlying_acc'])
        
        pd_acc.to_csv(os.path.join(dir_model,'accs_underlying_random_'+model_type+'_'+str(split_type)+'_'+str(split_i)+'.csv'))
    elif problem_type == 'regression':
        y_train = ds_sklearn.get('ds_train').get('y_train').astype(np.float32)
        y_val = ds_sklearn.get('ds_val').get('y_val').astype(np.float32)
        y_test = ds_sklearn.get('ds_test').get('y_test').astype(np.float32)
        
        if len(y_train.shape)==1:
            y_train = np.expand_dims(y_train,-1)
            y_val = np.expand_dims(y_val,-1)
            y_test = np.expand_dims(y_test,-1)
        
        error_random_train = np.sqrt(np.mean(np.sum((y_train[np.random.permutation(y_train.shape[0])]-y_train)**2,1),0)+1e-7)
        error_train = np.sqrt(np.mean(np.sum((y_train-y_hat_train)**2,1),0)+1e-7)
        
        error_random_val = np.sqrt(np.mean(np.sum((y_val[np.random.permutation(y_val.shape[0])]-y_val)**2,1),0)+1e-7)
        error_val = np.sqrt(np.mean(np.sum((y_val-y_hat_val)**2,1),0)+1e-7)
        
        error_random_test = np.sqrt(np.mean(np.sum((y_test[np.random.permutation(y_test.shape[0])]-y_test)**2,1),0)+1e-7)
        error_test = np.sqrt(np.mean(np.sum((y_test-y_hat_test)**2,1),0)+1e-7)
        
        print('\nerrors: train (random,wb)', np.round(error_random_train,2), np.round(error_train,2))
        print('errors: val (random,wb)', np.round(error_random_val,2), np.round(error_val,2))
        print('errors: test (random,wb)', np.round(error_random_test,2), np.round(error_test,2))
        
        pd_acc = pd.DataFrame([[error_random_train, error_train],
                               [error_random_val, error_val],
                               [error_random_test, error_test]],
                              index=['train_ds','val_ds','test_ds'],
                              columns=['random_underlying_rmse','model_underlying_rmse'])
        
        pd_acc.to_csv(os.path.join(dir_model,'errors_underlying_random_'+model_type+'_'+str(split_type)+'_'+str(split_i)+'.csv'))
    else:
        raise ValueError('supervised_tune_and_train: This problem_type is not implemented')
        
