def pipeline_step_2(model_type,n_splits,split_type,fit_all_splits,run_machine,experiment_name,dataset_name,
                    wd,optimizer_type,init_lr,lr_schedule,momentum,batch_size):
    start_time = time()
    
    if model_type == 'dnn':
        batches_per_epoch,epochs = get_batches_per_epoch_and_total_epochs(dataset_name=dataset_name,batch_size=batch_size)
        decay_steps = epochs*batches_per_epoch
    else:
        batches_per_epoch,epochs,decay_steps = None,None,None
    
    dir_superfix,dir_prefix = get_superfix_prefix_and_make_dir(run_machine=run_machine,experiment_name=experiment_name,overwrite_check=False)
    
    pred_dim_underlying,ds_dict = get_dataset(dataset_name=dataset_name) 
    
    if fit_all_splits:
        with open(os.path.join(dir_prefix,'data_splits','splits_'+split_type), 'rb') as f:
            splits = pickle.load(f)
        
        for split_i in range(n_splits):
            
            model = init_model(model_type=model_type,
                               arch_hyper_dict={'pred_dim':pred_dim_underlying,'n_base_nodes':16,'N':4,'k':2,'drop_p':0.0,'weight_decay':wd,
                                                'categorical_features_indicator_dict':ds_dict.get('categorical_indicator'),
                                                'categorical_features_vocabulary_size_dict':ds_dict.get('categorical_vocabulary_size_tensorflow'),
                                                'embedding_output_dim':1})
            if model_type == 'dnn':
                loss_fn = get_loss_function(problem_type=ds_dict.get('problem_type'))
                opt = get_optimizer(optimizer_type=optimizer_type,momentum=momentum,init_lr=init_lr,lr_schedule=lr_schedule,decay_steps=decay_steps)
            else:
                loss_fn,opt = None,None
            
            train_split = splits[split_i]
            supervised_tune_and_train(prefix=dir_prefix,model_type=model_type,model=model,ds_dict=ds_dict,pred_dim_underlying=pred_dim_underlying,
                                      train_split=train_split,split_type=split_type,split_i=split_i,
                                      batch_size=batch_size,epochs=epochs,loss_fn=loss_fn,opt=opt,
                                      save_name_params={'wd':str(wd),'opt':optimizer_type,'lr':str(init_lr),'sch':lr_schedule})
            
    model = init_model(model_type=model_type,
                       arch_hyper_dict={'pred_dim':pred_dim_underlying,'n_base_nodes':16,'N':4,'k':2,'drop_p':0.0,'weight_decay':wd,
                                        'categorical_features_indicator_dict':ds_dict.get('categorical_indicator'),
                                        'categorical_features_vocabulary_size_dict':ds_dict.get('categorical_vocabulary_size_tensorflow'),
                                        'embedding_output_dim':1})
    
    if model_type == 'dnn':
        loss_fn = get_loss_function(problem_type=ds_dict.get('problem_type'))
        opt = get_optimizer(optimizer_type=optimizer_type,momentum=momentum,init_lr=init_lr,lr_schedule=lr_schedule,decay_steps=decay_steps)
    else:
        loss_fn,opt = None,None
    
    n_train = ds_dict.get('ds_sklearn').get('ds_train').get('x_train').shape[0]
    train_split = tuple((np.arange(n_train,dtype=np.int32),np.arange(n_train,dtype=np.int32)))
    save_name_params={'wd':str(wd),'opt':optimizer_type,'lr':str(init_lr),'sch':lr_schedule}
    supervised_tune_and_train(prefix=dir_prefix,model_type=model_type,model=model,ds_dict=ds_dict,pred_dim_underlying=pred_dim_underlying,
                              train_split=train_split,split_type='nosplit',split_i='all',
                              batch_size=batch_size,epochs=epochs,loss_fn=loss_fn,opt=opt,
                              save_name_params=save_name_params)
    
    end_time = time()
    run_time = np.round((end_time-start_time)/60,2)
    print('total runtime (min):', run_time)
    
    if model_type == 'dnn':
        dir_model = os.path.join(dir_prefix,model_type+'_opt_'+save_name_params.get('opt')+'_sch_'+save_name_params.get('sch')+'_lr_'+save_name_params.get('lr')+'_wd_'+save_name_params.get('wd'))
    else:
        dir_model = os.path.join(dir_prefix,model_type)
    
    pd.DataFrame([[run_time]],columns=['total_run_time_min']).to_csv(os.path.join(dir_model,'pipeline_step_2_total_run_time.csv'))

